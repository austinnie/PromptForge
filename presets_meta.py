# 分类顺序（GUI 里按这个排）
CATEGORY_ORDER = ["机甲", "国风", "人像", "动漫", "素描", "动物", "设计", "风景", "其他"]


def get_display_name(preset_name: str) -> str:
    """返回 'mecha_glow — 机甲发光'"""
    meta = PRESET_META.get(preset_name)
    if meta:
        return f"{preset_name} — {meta[0]}"
    return preset_name


def get_category(preset_name: str) -> str:
    meta = PRESET_META.get(preset_name)
    return meta[1] if meta else "其他"


def get_presets_by_category() -> dict:
    """返回 {分类: [预设名列表]}"""
    from preset_bridge import preset_bridge
    all_presets = preset_bridge.list_presets()
    groups = {}
    for p in all_presets:
        cat = get_category(p)
        groups.setdefault(cat, []).append(p)
    # 按分类顺序排
    ordered = {}
    for cat in CATEGORY_ORDER:
        if cat in groups:
            ordered[cat] = sorted(groups[cat])
    return ordered